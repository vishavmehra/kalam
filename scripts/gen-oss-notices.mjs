// Builds src/features/settings/oss-notices-data.ts: the open-source packages Kalam ships with (direct
// dependencies of package.json, not dev tools) and the bundled font families, each with the licence the
// package itself declares. Run it after changing dependencies: node scripts/gen-oss-notices.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const licenseOf = (p) => (typeof p.license === 'string' ? p.license : p.license?.type ?? p.licenses?.map((l) => l.type).join(' OR ') ?? 'See package');

const rows = Object.keys(pkg.dependencies).sort((a, b) => a.localeCompare(b)).map((name) => {
  const p = JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'));
  // gsap's licence field is a sentence with a link; keep the name and drop the link.
  const license = licenseOf(p).replace(/:\s*https?:\/\/\S+/, '').replace(/\.$/, '');
  return `  { name: ${JSON.stringify(name)}, version: ${JSON.stringify(p.version)}, license: ${JSON.stringify(license)} },`;
});

const out = `/**
 * Generated by scripts/gen-oss-notices.mjs. Do not edit by hand: change package.json, then run the script again.
 * Direct dependencies only; each one's own dependencies carry their licences inside their packages.
 */
export interface OssNotice { name: string; version: string; license: string }

export const OSS_NOTICES: readonly OssNotice[] = [
${rows.join('\n')}
];

/** Font families bundled in assets/fonts (all SIL Open Font License 1.1). */
export const FONT_NOTICES: readonly { family: string; by: string }[] = [
  { family: 'Anek (all scripts)', by: 'Ek Type' },
  { family: 'Tiro (Devanagari, Bangla, Gurmukhi, Tamil, Telugu, Kannada)', by: 'Tiro Typeworks' },
  { family: 'Kalam', by: 'Indian Type Foundry' },
  { family: 'Courier Prime', by: 'Quote-Unquote Apps' },
  { family: 'Noto Serif Gujarati and Malayalam', by: 'The Noto Project Authors' },
];
`;
writeFileSync(join(root, 'src/features/settings/oss-notices-data.ts'), out);
console.log(`wrote ${rows.length} packages`);
